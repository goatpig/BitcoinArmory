void ScannerContext::update(ScrAddrFilter* saf)
{
   scrAddrIds_ = std::move(saf->getScrAddrIds());
}

const ScrAddrIdMap& ScannerContext::getScrAddrIdMap() const
{
   return scrAddrIds_;
}

