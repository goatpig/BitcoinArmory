// ScannerContext
void ScannerContext::init(LMDBBlockDatabase* db)
{
   if (!hashMap_.empty()) {
      throw std::runtime_error("hashmap isn't empty");
   }
   auto tx = db->beginTransaction(
      DB_SELECT::KNOWNHASHES, LMDB::Mode::ReadOnly);

   auto ldbIter = tx->getIterator();
   for (ldbIter.seekToFirst(); ldbIter.isValid(); ldbIter.advanceAndRead()) {
      auto keyRef = ldbIter.getKeyRef();
      if (keyRef.getSize() != 32) {
         //not a hash entry
         continue;
      }

      auto dataReader = ldbIter.getValueReader();
      std::set<uint64_t> vals;
      for (unsigned i = 0; i < dataReader.getSize() / 8; i++) {
         vals.emplace(dataReader.get_uint64_t());
      }
      hashMap_.emplace(Hash32{keyRef}, std::move(vals));
   }
}

void ScannerContext::merge(ScannerContext& incoming)
{
   //we only care to merge the hashMap from the incoming context
   //we also expect the incoming hashMap has a single txkey per hash
   //therefor, we can use update(hashMap) as is and ignore the return map
   update(incoming.hashMap_);
}

////////
HashMap ScannerContext::update(HashMap& incomingMap)
{
   /*
   We need to insert the known hashes found during the txout scan with
   the context's globla hash map.
   We also need to return the the of inserted hashes, so that they can
   be commited to the db.

   Since this data is updated by the output control thread and read
   by the input parser threads, we want to lock a mutex when updating
   the map and when grabbing it, to reflect changes across all reader
   threads.

   A known hash is a 32 bytes tx hash with it's associated txKey.
   Because of reorgs, the context map may carry multiple txKey for a
   given tx hash (if the tx appears in 2 different branches).
   The map generated by a txout scan always comes with a single key per
   tx hash.
   */
   std::unique_lock<std::mutex> lock(mu_);

   auto hashIter = incomingMap.begin();
   while (hashIter != incomingMap.end()) {
      //try to emplace the <hash, txKey> pair right away
      auto emplaceIter = hashMap_.emplace(
         hashIter->first, hashIter->second);

      if (emplaceIter.second == false) {
         //we already know this hash
         auto& txKeySet = emplaceIter.first->second;
         if (!txKeySet.emplace(*(hashIter->second.begin())).second) {
            //we already know this <hash, txKey> pair, clean up the
            //entry from the incoming map
            incomingMap.erase(hashIter++);
            continue;
         } else {
            //this <hash, blockID> pair is new, reflect the set back
            //into the incoming map
            hashIter->second = txKeySet;
         }
      }
      ++hashIter;
   }

   //at the end of this process, the incoming map should represent
   //all the <hash, blockID> pairs newly inserted
   return std::move(incomingMap);
}

const HashMap& ScannerContext::getHashMap() const
{
   //lock the mutex to reflect the map changes in caller thread
   std::unique_lock<std::mutex> lock(mu_);
   return hashMap_;
}

////////
void ScannerContext::update(std::shared_ptr<Blockchain> bc)
{
   headersById_ = bc->headersById();
}

bool ScannerContext::isBlockIDValid(uint32_t blockID) const
{
   if (blockID <= headersById_.size()) {
      return false;
   }
   return headersById_[blockID]->isMainBranch();
}

