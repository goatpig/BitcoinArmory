// BlockchainScanner
BlockchainScanner::BlockchainScanner(
   std::shared_ptr<Blockchain> bc, LMDBBlockDatabase* db,
   ScrAddrFilter* saf,
   std::shared_ptr<BlockFiles> bf,
   unsigned threadcount, unsigned memtarget,
   ProgressCallback prg, bool reportProgress) :
   blockchain_(bc), db_(db), scrAddrFilter_(saf),
   blockFiles_(bf),
   totalThreadCount_(threadcount), memTarget_(memtarget),
   totalBlockFileCount_(bf->fileCount()),
   progress_(prg), reportProgress_(reportProgress)
{
   fatalError_.store(0, std::memory_order_relaxed);
}

////////
bool BlockchainScanner::scan(ScannerContext& ctx, int32_t scanFrom)
{
   if (scanFrom > (int32_t)blockchain_->top()->getBlockHeight()) {
      return true;
   }

   //context prep
   TIMER_RESTART("scan_nocheck");
   ctx.update(scrAddrFilter_);
   ctx.update(blockchain_);

   startAt_ = scanFrom;
   auto topBlock = blockchain_->top();

   //start control threads
   std::thread commit_tID([this](){ commitBatches(); });
   std::thread outputs_tID([this](){ processOutputs(); });
   std::thread inputs_tID([this](){ processInputs(); });

   auto startHeight = scanFrom;
   unsigned endHeight = 0;

   std::vector<std::future<bool>> completedFutures;
   unsigned batchCount = 0;
   completedBatches_.store(0, std::memory_order_relaxed);

   //loop until there are no more blocks available
   try {
      unsigned firstBlockFileID = UINT32_MAX;
      unsigned targetBlockFileID = UINT32_MAX;

      while (startHeight <= (int32_t)topBlock->getBlockHeight()) {
         //figure out how many blocks to pull for this batch
         //batches try to grab up nBlockFilesPerBatch_ worth of block data
         unsigned targetHeight = 0;
         size_t targetSize = memTarget_ * BATCH_SIZE;
         size_t tallySize;
         try {
            std::shared_ptr<BlockHeader> currentHeader =
               blockchain_->getHeaderByHeight(startHeight);
            firstBlockFileID = currentHeader->getBlockFileId();

            targetBlockFileID = 0;
            targetHeight = startHeight;
            tallySize = currentHeader->getBlockSize();

            while (tallySize < targetSize) {
               currentHeader = blockchain_->getHeaderByHeight(++targetHeight);
               tallySize += currentHeader->getBlockSize();

               if (currentHeader->getBlockFileId() < firstBlockFileID) {
                  firstBlockFileID = currentHeader->getBlockFileId();
               }
               if (currentHeader->getBlockFileId() > targetBlockFileID) {
                  targetBlockFileID = currentHeader->getBlockFileId();
               }
            }
         } catch (const std::range_error& e) {
            //if getHeaderByHeight throws before targetHeight is topBlock's height,
            //something went wrong. Otherwise we just hit the end of the chain.

            if (targetHeight < topBlock->getBlockHeight()) {
               LOGERR << e.what();
               return false;
            } else {
               targetHeight = topBlock->getBlockHeight();
               if (targetBlockFileID < topBlock->getBlockFileId()) {
                  targetBlockFileID = topBlock->getBlockFileId();
               }
            }
         }
         endHeight = targetHeight;

         //create batch
         auto batch = std::make_unique<ParserBatch>(
            startHeight, endHeight,
            firstBlockFileID, targetBlockFileID,
            totalThreadCount_, ctx);
         completedFutures.push_back(batch->completedPromise.get_future());
         batch->count = batchCount;

         //post for txout parsing
         outputQueue_.push_back(move(batch));

         /***
         Throttle batch creation if we have more than writeQueueDepth_
         live batches.
         This had value when batches were using file maps. With file copies,
         the IO cost is front loaded in the batch lifetime and this step has
         no measurable effect currently.

         Disabled for now.
         ***/
         /*
         if (batchCount - completedBatches_.load(std::memory_order_relaxed) >=
            writeQueueDepth_) {
            try {
               auto futIter = completedFutures.begin() +
                  (batchCount - writeQueueDepth_);
               futIter->wait();
            } catch (const std::future_error &e) {
               LOGERR << "future error";
               return false;
            }
         }*/

         ++batchCount;
         startHeight = endHeight + 1;
      }
   } catch (const std::range_error&) {
      LOGERR << "failed to grab block data starting height: " << startHeight;
      if (startHeight == scanFrom) {
         LOGERR << "no block data was scanned";
      }
   } catch (...) {
      LOGWARN << "scanning halted unexpectedly";
      //let the scan terminate
   }

   //mark all queues complete
   outputQueue_.completed();

   if (outputs_tID.joinable()) {
      outputs_tID.join();
   }
   if (inputs_tID.joinable()) {
      inputs_tID.join();
   }
   if (commit_tID.joinable()) {
      commit_tID.join();
   }

   TIMER_STOP("scan_nocheck");
   if (topBlock->getBlockHeight() - scanFrom > 100) {
      auto timeSpent = TIMER_READ_SEC("scan_nocheck");
      LOGINFO << "scanned transaction history in " << timeSpent << "s";
      LOGINFO << " - filecopy: " << TIMER_READ_SEC("filecopy") << "s";
      LOGINFO << " - outputs: " << TIMER_READ_SEC("outputs") << "s";
      LOGINFO << " - inputs: " << TIMER_READ_SEC("inputs") << "s";
      LOGINFO << " - writer: " << TIMER_READ_SEC("write") << "s";
   }

   auto timeSpent = TIMER_READ_SEC("throttling");
   if (timeSpent > 5) {
      LOGINFO << "throttling for " << timeSpent << "s";
   }
   return fatalError_.load(std::memory_order_relaxed) == 0;
}

////////
void BlockchainScanner::processOutputs()
{
   TIMER_RESET("throttling");
   TIMER_RESET("outputs");
   TIMER_RESET("filecopy");

   auto process_thread = [this](ParserBatch* batch)->void
   {
      this->processOutputsThread(batch);
   };


   //init batch
   std::map<Types::FileId, std::shared_ptr<FileUtils::FileCopy>> localFileCopies;
   std::unique_ptr<ParserBatch> batch;
   while (true) {
      try {
         batch = std::move(outputQueue_.pop_front());
         break;
      } catch (const Threading::StopBlockingLoop&) {}
   }

   auto preloadFut = batch->preloadFiles(
      blockFiles_, localFileCopies);
   while (true) {
      //wait till files are loaded
      preloadFut.wait();

      //start processing threads
      TIMER_START("outputs");
      std::vector<std::thread> thr_vec;
      thr_vec.reserve(totalThreadCount_);
      for (unsigned i = 0; i < totalThreadCount_; i++) {
         thr_vec.emplace_back(std::thread(process_thread, batch.get()));
      }

      TIMER_START("throttling");
      std::unique_ptr<ParserBatch> nextBatch;
      try {
         nextBatch = std::move(outputQueue_.pop_front());
      } catch (const Threading::StopBlockingLoop&) {}
      TIMER_STOP("throttling");

      //populate the next batch's file map while the first
      //batch is being processed
      if (nextBatch != nullptr) {
         preloadFut = nextBatch->preloadFiles(
            blockFiles_, localFileCopies);
      }

      //wait on threads
      for (auto& thr : thr_vec) {
         if (thr.joinable()) {
            thr.join();
         }
      }
      TIMER_STOP("outputs");

      //push first batch for input processing
      inputQueue_.push_back(std::move(batch));

      //check loop break condition
      if (nextBatch == nullptr || fatalError_.load(std::memory_order_relaxed) != 0) {
         break;
      }

      //set batch for next iteration
      batch = std::move(nextBatch);
   }

   //done with processing ouputs, there won't be anymore batches to push
   //to the input queue, we can mark it complete
   inputQueue_.completed();
}

void BlockchainScanner::processInputs()
{
   TIMER_RESET("inputs");

   auto process_thread = [this](ParserBatch* batch)->void
   {
      this->processInputsThread(batch);
   };

   while (true) {
      std::unique_ptr<ParserBatch> batch;
      try {
         batch = std::move(inputQueue_.pop_front());
      } catch (const Threading::StopBlockingLoop&) {
         //end condition
         break;
      }

      if (fatalError_.load(std::memory_order_relaxed) != 0) {
         //fatal error in the batch, stop whole scan
         commitQueue_.completed();
         return;
      }

      //reset counter
      TIMER_START("inputs");
      batch->blockCounter.store(batch->start, std::memory_order_relaxed);

      //merge utxo map from batch with global one
      //this data needs copied because we still have use for the original map
      batch->inParserResult.diff =
         batch->context.update(batch->outParserResult.hashMap);

      //start processing threads
      std::vector<std::thread> thr_vec;
      for (unsigned i = 1; i < totalThreadCount_; i++) {
         thr_vec.emplace_back(std::thread(process_thread, batch.get()));
      }
      process_thread(batch.get());

      //wait on threads
      for (auto& thr : thr_vec) {
         if (thr.joinable()) {
            thr.join();
         }
      }

      //push for commit
      commitQueue_.push_back(std::move(batch));
      TIMER_STOP("inputs");
   }

   //done with processing inputs, there won't be anymore batches to push
   //to the commit queue, we can mark it complete
   commitQueue_.completed();
}

////////
std::shared_ptr<BlockData> BlockchainScanner::getBlockData(
   ParserBatch* batch, unsigned height)
{
   //grab block file map
   auto blockheader = blockchain_->getHeaderByHeight(height);
   auto filenum = blockheader->getBlockFileId();
   auto mapIter = batch->fileCopies.find(filenum);
   if (mapIter == batch->fileCopies.end()) {
      LOGERR << "Missing file map for output scan, this is unexpected";
      LOGERR << "Has the following block files:";
      for (const auto& file_pair : batch->fileCopies) {
         LOGERR << " --- #" << file_pair.first;
      }
      LOGERR << "Was looking for id #" << filenum;
      throw std::runtime_error("missing file map");
   }

   auto filemap = mapIter->second.get();
   if (!filemap->isValid()) {
      LOGERR << "Invalid FileMap for height " << height;
      throw std::runtime_error("Invalid FileMap");
   }

   try {
      auto bdata = BlockData::deserialize(
         filemap->ptr() + blockheader->getOffset(),
         blockheader->getBlockSize(),
         blockheader, BlockData::CheckHashes::NoChecks);
      return bdata;
   } catch (const std::exception&) {
      blockchain_->flagBlockHeader(blockheader, db_);
      return nullptr;
   }
}

////////
void BlockchainScanner::processOutputsThread(ParserBatch* batch)
{
   TxOutParsingResult result;

   auto scrAddrIdMap = batch->context.getScrAddrIdMap();
   while (true) {
      //shutdown all output workers if the batch encountered a fatal error
      if (fatalError_.load(std::memory_order_relaxed) != 0) {
         return;
      }

      auto currentBlock = batch->blockCounter.fetch_add(
         1, std::memory_order_relaxed);
      if (currentBlock > batch->end) {
         break;
      }

      auto blockdata = getBlockData(batch, currentBlock);
      if (blockdata == nullptr) {
         LOGERR << "Could not get block data for height #" << currentBlock;
         fatalError_.store(1, std::memory_order_relaxed);
         return;
      }
      result.blockMap.emplace(currentBlock, blockdata);

      const auto header = blockdata->getHeaderPtr();
      const auto& txns = blockdata->getTxns();
      for (size_t i = 0; i < txns.size(); i++) {
         const BCTX& txn = *(txns[i].get());
         for (size_t y = 0; y < txn.txouts_.size(); y++) {
            const auto& txout = txn.txouts_[y];

            BinaryRefReader brr{txn.data_ + txout.first, txout.second};
            brr.advance(8);
            unsigned scriptSize = (unsigned)brr.get_var_int();
            if (scriptSize == 0) {
               continue;
            }
            auto scrAddr = BtcUtils::getTxOutScrAddr(
               brr.get_BinaryDataRef(scriptSize));

            auto saIter = scrAddrIdMap.find(scrAddr);
            if (saIter == scrAddrIdMap.end()) {
               continue;
            }
            /* if we got this far, this txout is ours */

            //track known hash and its txkey
            auto txKey = Types::constructTxKey(header->getUniqueID(), i);
            const auto& txHash = txn.getHash();
            result.hashMap.emplace(txHash, std::set<uint64_t>{txKey});

            //track txout data via scrAddr unique id
            const auto& scrAddrUniqueId = saIter->second;
            auto txOutIter = result.txOutMap.find(scrAddrUniqueId);
            if (txOutIter == result.txOutMap.end()) {
               txOutIter = result.txOutMap.emplace(scrAddrUniqueId,
                  std::map<Types::BlockId, std::deque<TxOutData>>{}).first;
            }

            //get tx out value from script
            brr.resetPosition();
            uint64_t value = brr.get_uint64_t();

            //append to txout deque
            auto emplaceResult = txOutIter->second.emplace(
               header->getUniqueID(), std::deque<TxOutData>{}).first;
            emplaceResult->second.emplace_back(TxOutData{
               value, header->getUniqueID(), (uint16_t)i, (uint16_t)y});
         }
      }
   }

   //merge thread result to batch result
   batch->mergeResult(result);
}

void BlockchainScanner::processInputsThread(ParserBatch* batch)
{
   TxInParsingResult result;

   const auto& hashMap = batch->context.getHashMap();
   while (true) {
      //shutdown all input workers if the batch encountered a fatal error
      if (fatalError_.load(std::memory_order_relaxed) != 0) {
         return;
      }

      auto currentBlock = batch->blockCounter.fetch_add(
         1, std::memory_order_relaxed);

      if (currentBlock > batch->end) {
         break;
      }

      auto blockDataIter = batch->outParserResult.blockMap.find(currentBlock);
      if (blockDataIter == batch->outParserResult.blockMap.end()) {
         LOGERR << "can't find block #" << currentBlock << " in batch";
         fatalError_.store(1, std::memory_order_relaxed);
         return;
      }

      auto blockdata = blockDataIter->second;
      const auto header = blockdata->getHeaderPtr();
      const auto& txns = blockdata->getTxns();

      for (size_t i = 0; i < txns.size(); i++) {
         const BCTX& txn = *(txns[i].get());

         for (size_t y = 0; y < txn.txins_.size(); y++) {
            const auto& txin = txn.txins_[y];
            BinaryDataRef outHash(txn.data_ + txin.first, 32);
            auto hashIter = hashMap.find(outHash);
            if (hashIter == hashMap.end()) {
               continue;
            }

            /*
            We know this tx hash. Track the input.

            Optimization trick: we track all inputs that consume a known
            hash, regardless of txOut index matching.

            This txIn may or may not affect our known scrAddr, but since
            we do not tie txIns to scrAddr, only txOuts, we do not need to
            know.

            This cuts on a lot of complexity for context bootstrap:
             - it's easy to know which txhash affects us
             - it's hard to know which outputs within the tx affect us

            The extra data is negligible.
            */
            uint64_t txKey = *(hashIter->second.begin());
            if (hashIter->second.size() != 1) {
               //multiple blocks carry this hash, grab the valid one
               txKey = UINT64_MAX;
               for (const auto& key : hashIter->second) {
                  auto blockID = Types::getBlockIDFromScrAddrKey(key);
                  if (batch->context.isBlockIDValid(blockID)) {
                     txKey = key;
                     break;
                  }
               }
               if (txKey == UINT64_MAX) {
                  //this should never happen
                  throw std::runtime_error(
                     "could not find a valid block for this hash!");
               }
            }

            //create keys, add to result map
            uint32_t outpointId;
            memcpy(&outpointId, txn.data_ + txin.first + 32, 4);
            uint64_t txOutKey = Types::constructTxIOKeyFromTxKey(txKey, (uint16_t)outpointId);
            uint64_t txInKey = Types::constructTxIOKey(header->getUniqueID(), i, y);
            result.txInMap.emplace(txOutKey, txInKey);
         }
      }
   }

   //merge process data into batch
   batch->mergeResult(result);
}

////////
void BlockchainScanner::commitBatches()
{
   auto getGlobalOffsetForBlock = [bc=blockchain_](unsigned height)->size_t
   {
      auto header = bc->getHeaderByHeight(height);
      size_t val = header->getBlockFileId();
      val *= 128 * 1024 * 1024;
      val += header->getOffset();
      return val;
   };

   ProgressCalculator calc(getGlobalOffsetForBlock(
      blockchain_->top()->getBlockHeight()));
   auto initVal = getGlobalOffsetForBlock(startAt_);
   calc.init(initVal);
   if (reportProgress_) {
      progress_(BDMPhase_Rescan,
      calc.fractionCompleted(), UINT32_MAX,
      initVal);
   }

   TIMER_RESET("write");

   while (true) {
      std::unique_ptr<ParserBatch> batch;
      try {
         batch = std::move(commitQueue_.pop_front());
      } catch (const Threading::StopBlockingLoop&) {
         break;
      }

      TIMER_START("write");

      //sanity check
      auto& outData = batch->outParserResult;
      if (outData.blockMap.empty()) {
         TIMER_STOP("write");
         continue;
      }

      /* serialize the data */

      auto topheader = outData.blockMap.rbegin()->second->getHeaderPtr();
      if (topheader == nullptr) {
         LOGERR << "empty top block header ptr, aborting scan";
         throw std::runtime_error("nullptr header");
      }

      //txouts
      std::map<uint64_t, BinaryWriter> serializedTxOuts;
      for (const auto& txoutPair : outData.txOutMap) {
         for (const auto& blockIdPair : txoutPair.second) {
            auto saKey = Types::constructScrAddrKey(txoutPair.first, blockIdPair.first);
            auto emplaceIter = serializedTxOuts.emplace(
               saKey, BinaryWriter{12 * blockIdPair.second.size()}).first;
            auto& bw = emplaceIter->second;
            for (const auto& txout : blockIdPair.second) {
               bw.put_uint64_t(txout.amount);
               bw.put_uint16_t(txout.txId);
               bw.put_uint16_t(txout.txOutId);
            }
         }
      }

      //txins are serialized in place at creation time
      auto& inData = batch->inParserResult;
      auto serializedTxIns = std::move(inData.txInMap);

      //known hashes
      std::map<Hash32, BinaryWriter> serializedHashes;
      for (auto& hashPair : inData.diff) {
         auto iter = serializedHashes.emplace(std::move(hashPair.first),
            BinaryWriter{hashPair.second.size() * sizeof(uint64_t)}).first;
         auto& bw = iter->second;
         for (const auto& key : hashPair.second) {
            bw.put_uint64_t(key);
         }
      }

      /* write the data */

      //txouts
      {
         auto tx = db_->beginTransaction(
            DB_SELECT::TXOUTS, LMDB::Mode::ReadWrite);
         for (const auto& txoPair : serializedTxOuts) {
            LMDB::DataRef keyRef{sizeof(uint64_t), (const uint8_t*)&txoPair.first};
            auto valBdr = txoPair.second.getDataRef();
            LMDB::DataRef valRef{valBdr.getSize(), valBdr.getPtr()};
            tx->insert(keyRef, valRef);
         }
      }

      //txins
      {
         auto tx = db_->beginTransaction(
            DB_SELECT::TXINS, LMDB::Mode::ReadWrite);
         for (const auto& txiPair : serializedTxIns) {
            LMDB::DataRef keyRef{sizeof(uint64_t), (const uint8_t*)&txiPair.first};
            LMDB::DataRef valRef{sizeof(uint64_t), (const uint8_t*)&txiPair.second};
            tx->insert(keyRef, valRef);
         }
      }

      //known hashes
      {
         auto tx = db_->beginTransaction(
            DB_SELECT::KNOWNHASHES, LMDB::Mode::ReadWrite);
         for (const auto& khPair : serializedHashes) {
            LMDB::DataRef keyRef{32, (const uint8_t*)khPair.first.data};
            auto valBdr = khPair.second.getDataRef();
            LMDB::DataRef valRef{valBdr.getSize(), valBdr.getPtr()};
            tx->insert(keyRef, valRef);
         }
      }

      if (batch->start != batch->end) {
         LOGINFO << "scanned from block #" << batch->start
            << " to #" << batch->end;
      } else {
         LOGINFO << "scanned block #" << batch->start;
      }

      size_t progVal = getGlobalOffsetForBlock(batch->end);
      calc.advance(progVal);
      if (reportProgress_) {
         progress_(BDMPhase_Rescan,
         calc.fractionCompleted(), calc.remainingSeconds(),
         progVal);
      }
      topScannedBlockHash_ = topheader->getThisHash();

      completedBatches_.fetch_add(1, std::memory_order_relaxed);
      batch->completedPromise.set_value(true);

      TIMER_STOP("write");
   }
}

////////
void BlockchainScanner::processFilterHitsThread(
   std::map<uint32_t, std::map<uint32_t, std::set<const TxHashHints*>>>& filtersResultMap,
   const std::set<BinaryData>& missingHashes, std::atomic<int>& counter,
   std::map<BinaryData, BinaryData>& results,
   std::function<void(size_t)>)
{
   std::map<BinaryData, BinaryData> result;
   uint32_t missedBlocks = 0;

   auto resolveHashes =
      [&](uint32_t fileNum,
      std::map<uint32_t, std::set<const TxHashHints*>> filterHit,
      std::set<BinaryData>& hashSet)->void
   {
      auto filePath = blockFiles_->getFilePathForID(fileNum);
      FileUtils::FileMap fileMap(filePath);

      for (auto& blockkey : filterHit) {
         std::shared_ptr<BlockHeader> headerPtr;
         try {
            headerPtr = blockchain_->getHeaderById(blockkey.first);
         } catch (const std::range_error&) {
            //no block for this id, this is an orphan
            missedBlocks++;
            continue;
         }

         //search the block
         std::shared_ptr<BlockData> bdata;
         try {
            bdata = BlockData::deserialize(
               fileMap.ptr() + headerPtr->getOffset(),
               headerPtr->getBlockSize(),
               headerPtr, BlockData::CheckHashes::NoChecks);
         } catch (const BtcUtils::BlockDeserializingException& e) {
            LOGERR << "Block deser error while processing tx filters: ";
            LOGERR << "  " << e.what();
            LOGERR << "Skipping this block";
            continue;
         }

         const auto& txns = bdata->getTxns();
         for (const auto& filterhit : blockkey.second) {
            auto iditer = filterhit->filterHits_.find(blockkey.first);
            if (iditer == filterhit->filterHits_.end()) {
               continue;
            }

            const auto& txids = iditer->second;
            for (auto& txid : txids) {
               if (txid >= txns.size()) {
                  continue;
               }
               const auto& txn = txns[txid];
               const auto& txnHash = txn->getHash();

               auto hashIter = hashSet.begin();
               while (hashIter != hashSet.end()) {
                  if (txnHash == *hashIter) {
                     auto countAndHash = WRITE_UINT32_LE(txids.size());
                     countAndHash.append(txnHash);
                     result[countAndHash] = std::move(
                        DBUtils::getBlkDataKeyNoPrefix(
                        headerPtr->getBlockHeight(),
                        0,
                        txid));

                     hashSet.erase(hashIter++);
                     continue;
                  }
                  ++hashIter;
               }
            }
         }
      }
   };

   auto missingHashesCopy = missingHashes;
   while (true) {
      auto index = counter.fetch_sub(1, std::memory_order_relaxed);
      if (index < 0) {
         break;
      }
      auto filterIter = filtersResultMap.find(index);

      auto& blkHitsMap = filterIter->second;
      auto hitsPairIter = blkHitsMap.begin();
      while (hitsPairIter != blkHitsMap.end()) {
         auto& txFilterSet = hitsPairIter->second;

         auto hitsIter = txFilterSet.begin();
         while (hitsIter != txFilterSet.end()) {
            auto hashIter = missingHashesCopy.find((*hitsIter)->hash_);
            if (hashIter != missingHashesCopy.end()) {
               ++hitsIter;
               continue;
            }
            txFilterSet.erase(hitsIter++);
         }

         if (!txFilterSet.empty()) {
            ++hitsPairIter;
            continue;
         }
         blkHitsMap.erase(hitsPairIter++);
      }

      if (blkHitsMap.empty()) {
         continue;
      }
      resolveHashes(filterIter->first, filterIter->second, missingHashesCopy);
   }

   //merge results
   std::unique_lock<std::mutex> lock(resolverMutex_);
   results.insert(result.begin(), result.end());
}

